<h2 id="h1">1. تسجيل الدخول والجلسة</h2>
<ul>
<li>افتح <b dir="ltr">al-khadraa.com/store/admin/</b> وسجّل الدخول باسم المستخدم وكلمة المرور الخاصة بالمدير.</li>
<li>بعد 8 محاولات خاطئة يُمنع الدخول لمدة 15 دقيقة.</li>
<li>تُغلق الجلسة بعد 60 دقيقة دون نشاط. سجّل الدخول مرة أخرى؛ لا يضيع شيء.</li>
<li>بدّل اللغة من زر <b>عربي / English</b> في الشريط العلوي.</li>
</ul>

<h2 id="h2">2. سجل طلبات التسعير</h2>
<ul>
<li>كل طلب تسعير يُرسل من المتجر (الصفحة العربية أو الإنجليزية) يظهر هنا، الأحدث أولاً. وتستلم IES كل طلب أيضاً بالبريد الإلكتروني على <span dir="ltr">info@ies-iraq.com</span>.</li>
<li>المربعات الملونة تعرض عدد الطلبات حسب الحالة. اضغط على مربع لعرض تلك الحالة فقط، واضغط <b>الكل</b> لعرض الجميع.</li>
<li>البحث يجد رقم الطلب والشركة وجهة الاتصال والهاتف والبريد وأي رقم قطعة أو وصف في المواد.</li>
</ul>

<h2 id="h3">3. فتح الطلب والرد على الزبون</h2>
<ul>
<li>اضغط على السطر لفتح الطلب: بيانات الزبون والرسالة وقائمة المواد (المصدر: <span dir="ltr">STOCK</span> = مخزن بغداد، <span dir="ltr">SUP</span> = أجهزة Supmea، <span dir="ltr">SPR</span> = قطع الغيار القديمة، <span dir="ltr">BOM</span> = قائمة ملصوقة).</li>
<li>اضغط على رقم الهاتف لفتح واتساب، أو على البريد الإلكتروني لكتابة رسالة برقم الطلب في العنوان.</li>
<li>جهّز عرض السعر حسب طريقة IES المعتادة (ورقة التقدير، العرض على الورق الرسمي). الهدف هو الرد خلال يوم عمل واحد (السبت–الخميس).</li>
</ul>

<h2 id="h4">4. الحالة والملاحظات الداخلية</h2>
<ul>
<li>الحالات: <b>جديد</b> ← <b>قيد المعالجة</b> ← <b>أُرسل العرض</b> ← <b>فاز</b> أو <b>خسر</b>؛ و<b>مغلق</b> للطلبات التي لا تحتاج إجراءً (رسائل مزعجة، مكررة، ملغاة).</li>
<li>اختر الحالة، واكتب ملاحظة عند الحاجة (رقم العرض، السعر، موعد المتابعة) ثم اضغط <b>حفظ</b>. الملاحظات داخلية ولا يراها الزبون.</li>
<li>كل تغيير يُسجَّل بالتاريخ واسم المستخدم. لا يمكن تعديل الملاحظات أو حذفها – أضف ملاحظة جديدة للتصحيح.</li>
</ul>

<h2 id="h5">5. التصدير إلى Excel</h2>
<ul>
<li>زر <b>تصدير إلى Excel</b> ينزّل السجل كاملاً: ورقة <span dir="ltr">RFQs</span> (سطر لكل طلب مع الحالة والملاحظات)، وورقة <span dir="ltr">Lines</span> (سطر لكل مادة)، وورقة <span dir="ltr">Info</span>.</li>
<li>استخدمه لاجتماعات المتابعة وتقارير المبيعات وكنسخة إضافية على OneDrive.</li>
</ul>

<h2 id="h6">6. النسخ الاحتياطي</h2>
<ul>
<li>تُعمل نسخة احتياطية تلقائياً عند أول تسجيل دخول في كل يوم وقبل كل استعادة. اضغط <b>احفظ نسخة احتياطية الآن</b> لنسخة إضافية (مثلاً قبل تحديث الموقع).</li>
<li>كل ملف ZIP يحتوي على جميع ملفات الطلبات وملف الحالات والملاحظات وسجل التدقيق وسجل Excel. يُحتفظ بأحدث 30 نسخة على الخادم.</li>
<li>نزّل نسخة احتياطية مرة في الشهر على الأقل واحفظها في <b dir="ltr">OneDrive\Documents\IES Online Store\Backup</b>.</li>
</ul>

<h2 id="h7">7. الاستعادة من نسخة احتياطية</h2>
<ol>
<li>افتح <b>النسخ الاحتياطي والاستعادة</b>، اختر ملف النسخة الاحتياطية واضغط <b>رفع وفحص</b>.</li>
<li>اقرأ تقرير الفحص: الأخطاء، التحذيرات، الطلبات التي ستُضاف، والطلبات الموجودة أصلاً.</li>
<li>إذا كان التقرير صحيحاً اكتب <b dir="ltr">RESTORE</b> واضغط <b>تطبيق الاستعادة</b>.</li>
</ol>
<p>الاستعادة تضيف الطلبات المفقودة فقط (مع حالتها وملاحظاتها)، ولا تغيّر أو تحذف أي طلب موجود. تُعمل نسخة احتياطية تلقائياً قبل الاستعادة مباشرة.</p>

<h2 id="h8">8. سجل التدقيق</h2>
<p>يعرض آخر 200 إجراء: تسجيل الدخول (والمحاولات الفاشلة)، تغيير الحالات، التصدير، النسخ الاحتياطي، التنزيل والاستعادة، مع الوقت (UTC) والمستخدم والتفاصيل.</p>

<h2 id="h9">9. كلمة المرور وفقدان الدخول</h2>
<ul>
<li>غيّر كلمة المرور من صفحة <b>الحساب</b> (10 أحرف على الأقل).</li>
<li>إذا فُقدت كلمة المرور: في GoDaddy cPanel › File Manager افتح <b dir="ltr">public_html/store/api/data/</b> واحذف الملف <b dir="ltr">admin_config.php</b> وأنشئ ملفاً فارغاً باسم <b dir="ltr">SETUP_ALLOWED</b>. ثم افتح صفحة الإدارة وأنشئ الحساب من جديد. طلبات التسعير لا تتأثر.</li>
</ul>

<h2 id="h10">10. أين تُحفظ البيانات</h2>
<ul>
<li>مجلد الخادم <b dir="ltr">public_html/store/api/data/</b> (مغلق أمام الإنترنت): ملف JSON لكل طلب، وملف <span dir="ltr">status.json</span>، و<span dir="ltr">audit.log</span>، ومجلد <span dir="ltr">backups/</span>.</li>
<li>لا تحذف هذا المجلد أبداً عند تحديث الموقع. حزمة تحديث الموقع لا تحتوي عليه.</li>
</ul>
